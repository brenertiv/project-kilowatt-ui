function writeGuides() {
  const dir = join(out, 'guides');
  mkdirSync(dir, { recursive: true });
  const docsDir = join(root, 'docs');
  let count = 0;
  for (const file of readdirSync(docsDir).filter((name) => name.endsWith('.md') && !internalDocs.has(name)).sort()) {
    const markdown = readFileSync(join(docsDir, file), 'utf8');
    const heading = /^#\s+(.+)$/m.exec(markdown)?.[1]?.trim() ?? file.replace(/\.md$/, '');
    const title = `Guides/${guideTitles[file] ?? heading}`;
    const body = `${markdownToMdx(markdown)}\n\n---\n\nSource: \`docs/${file}\`.`;
    writeFileSync(join(dir, file.replace(/\.md$/, '.mdx')), page({ title, summary: firstParagraph(markdown), body }));
    count += 1;
  }
  return count;
}

rmSync(out, { recursive: true, force: true });
const counts = { foundations: writeDepartures() + writeChartDepartures() + writeMapDepartures() + writeFoundations() + writeIcons(), guides: writeGuides() };
console.log(`build-docs: ${counts.foundations} foundations pages, ${counts.guides} guides in src/docs/generated`);
