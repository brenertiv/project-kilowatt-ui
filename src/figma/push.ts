import { tokens, type Token } from '../tokens';
import { figmaAliasTarget, figmaSnapshot, type FigmaSnapshot } from './snapshot';

/**
 * The code-to-Figma direction. Tokens that code owns (tints, utilities, chart
 * slots, the neutral track, the divider steps) are expressed as primitive
 * steps per mode in `tokens.ts`. This module turns them into a Plugin API
 * script that writes a `code` collection in the Figma file, each variable an
 * alias to the primitive it names, and compares that intent with the last
 * snapshot so the System page can say what is still to push.
 */

export const codeCollection = 'code';

export type PushEntry = {
  token: Token;
  /** Variable name in the `code` collection: the CSS variable with its dashes turned into a path, e.g. `chart/1`. */
  name: string;
  /** Primitive paths, e.g. `color/brand/50`. */
  light: string;
  dark: string;
};

export type PushStatus = 'missing' | 'changed' | 'synced';

export type PushPlanEntry = PushEntry & {
  status: PushStatus;
  /** What the snapshot has for this variable, as primitive paths, when it exists. */
  figmaLight?: string;
  figmaDark?: string;
};

export function codeVariableName(token: Token): string {
  return token.cssVar.replace(/^--/, '').replace(/-/g, '/');
}

export function pushEntries(source: Token[] = tokens): PushEntry[] {
  return source
    .filter((token) => token.type === 'color' && token.primitive)
    .map((token) => ({
      token,
      name: codeVariableName(token),
      light: token.primitive!.light,
      dark: token.primitive!.dark,
    }));
}

function stripCollection(path: string | undefined) {
  return path?.replace(/^primitives\//, '');
}

/** Each code-owned token against the `code` collection in the snapshot, plus variables there that code no longer declares. */
export function pushPlan(entries: PushEntry[] = pushEntries(), snapshot: FigmaSnapshot = figmaSnapshot) {
  const collection = snapshot.collections[codeCollection];
  const seen = new Set<string>();
  const plan: PushPlanEntry[] = entries.map((entry) => {
    seen.add(entry.name);
    if (!collection?.variables[entry.name]) return { ...entry, status: 'missing' };
    const figmaLight = stripCollection(figmaAliasTarget(`${codeCollection}/${entry.name}`, 'Light', snapshot));
    const figmaDark = stripCollection(figmaAliasTarget(`${codeCollection}/${entry.name}`, 'Dark', snapshot));
    const status: PushStatus = figmaLight === entry.light && figmaDark === entry.dark ? 'synced' : 'changed';
    return { ...entry, status, figmaLight, figmaDark };
  });
  const extras = Object.keys(collection?.variables ?? {}).filter((name) => !seen.has(name));
  return { entries: plan, extras, pending: plan.filter((entry) => entry.status !== 'synced').length };
}

/**
 * The script to run in the Figma file through the connector (`use_figma`).
 * Idempotent: creates the collection and its Light and Dark modes when they
 * are missing, creates or updates one variable per entry as an alias to the
 * primitive, and reports variables in the collection that code no longer
 * declares without deleting them.
 */
export function pushScript(entries: PushEntry[] = pushEntries()): string {
  const rows = entries.map((entry) => JSON.stringify([entry.name, entry.light, entry.dark]));
  return `// Generated by project-kilowatt-ui from src/tokens.ts. Writes the code-owned tokens into the "${codeCollection}" collection.
const NAME = ${JSON.stringify(codeCollection)};
const ENTRIES = [
  ${rows.join(',\n  ')},
];
const collections = await figma.variables.getLocalVariableCollectionsAsync();
const variables = await figma.variables.getLocalVariablesAsync();
const primitives = collections.find((c) => c.name === 'primitives');
if (!primitives) throw new Error('No "primitives" collection in this file');
const primitiveByName = new Map(variables.filter((v) => v.variableCollectionId === primitives.id).map((v) => [v.name, v]));
let code = collections.find((c) => c.name === NAME);
const result = { collectionId: null, createdCollection: false, created: [], updated: [], extra: [] };
if (!code) {
  code = figma.variables.createVariableCollection(NAME);
  result.createdCollection = true;
}
result.collectionId = code.id;
if (!code.modes.some((m) => m.name === 'Light')) code.renameMode(code.modes[0].modeId, 'Light');
const light = code.modes.find((m) => m.name === 'Light').modeId;
const dark = code.modes.find((m) => m.name === 'Dark')?.modeId ?? code.addMode('Dark');
const existing = new Map(variables.filter((v) => v.variableCollectionId === code.id).map((v) => [v.name, v]));
for (const [name, lightPath, darkPath] of ENTRIES) {
  const lightPrimitive = primitiveByName.get(lightPath);
  const darkPrimitive = primitiveByName.get(darkPath);
  if (!lightPrimitive || !darkPrimitive) throw new Error(\`Primitive missing for \${name}: \${lightPath} / \${darkPath}\`);
  let variable = existing.get(name);
  if (variable) {
    result.updated.push(name);
    existing.delete(name);
  } else {
    variable = figma.variables.createVariable(name, code, 'COLOR');
    variable.scopes = ['ALL_SCOPES'];
    result.created.push(name);
  }
  variable.description = 'Code-owned: pushed from project-kilowatt-ui (src/tokens.ts). Change it there, not here.';
  variable.setValueForMode(light, figma.variables.createVariableAlias(lightPrimitive));
  variable.setValueForMode(dark, figma.variables.createVariableAlias(darkPrimitive));
}
result.extra = [...existing.keys()];
return result;
`;
}
